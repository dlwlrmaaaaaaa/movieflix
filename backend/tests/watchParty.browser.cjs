const assert = require('node:assert/strict');
const path = require('node:path');
const { chromium } = require(process.env.TF_PLAYWRIGHT_PATH || path.join(require('node:os').tmpdir(), 'togetherflix-ui-tools/node_modules/playwright'));
const base = 'http://localhost:4109';
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--autoplay-policy=no-user-gesture-required'] });
  const errors = [];
  const context = async (user, viewport) => {
    const session = await (await fetch(`${base}/__test/session/${user}`)).json();
    const instance = await browser.newContext({ viewport, permissions: ['clipboard-read', 'clipboard-write'] });
    await instance.addInitScript(({ accessToken, user }) => { if (!localStorage.getItem('@togetherflix_access_token')) { localStorage.setItem('@togetherflix_access_token', accessToken); localStorage.setItem('@togetherflix_user_profile', JSON.stringify(user)); } }, session);
    const page = await instance.newPage(); page.on('pageerror', (error) => errors.push(error.message));
    return page;
  };
  try {
    let host = await context('host', { width: 1440, height: 1080 });
    const guest = await context('guest', { width: 390, height: 844 });
    await host.goto(`${base}/home`);
    await host.getByText('Watch Party', { exact: true }).filter({ visible: true }).waitFor();
    assert.equal(await host.title(), 'AnnahFlix');
    assert.equal(await host.getByText('Create Movie Room', { exact: true }).count(), 0);
    await host.getByText('Authorized test movie', { exact: true }).first().click();
    await host.waitForURL(/\/movie\/550$/);
    await host.getByText('Watch Now', { exact: true }).filter({ visible: true }).click();
    await host.locator('iframe').waitFor();
    assert.equal(await host.getByText('Watch with Party', { exact: true }).filter({ visible: true }).count(), 0);
    assert.equal(await host.getByText('Copy Room Code', { exact: true }).count(), 0);
    await host.getByText('Second Test', { exact: true }).filter({ visible: true }).click();
    await host.waitForFunction(() => document.querySelector('iframe')?.src.includes('server=second'));
    await host.goto(`${base}/movie/550`);
    await host.getByText('Watch with Party', { exact: true }).filter({ visible: true }).click();
    await host.waitForURL(/\/room\/TF-/);
    await host.locator('iframe').waitFor();
    assert.equal(await host.getByText('Camera on', { exact: true }).count(), 0);
    assert.equal(await host.getByText('Room chat', { exact: true }).count(), 0);
    assert.equal(await host.getByText('Start Screen Share', { exact: true }).count(), 0);
    const code = host.url().match(/\/room\/(TF-[A-Z2-9]{4})/)[1];
    await host.getByText('Copy Room Code', { exact: true }).click();
    assert.equal(await host.evaluate(() => navigator.clipboard.readText()), code);
    await guest.goto(`${base}/join`);
    await guest.getByPlaceholder('TF-AB23').fill(code);
    await guest.getByText('Join Room', { exact: true }).click();
    await guest.waitForURL(new RegExp(`/room/${code}`));
    await guest.getByText('Waiting for the host to start the movie', { exact: true }).first().waitFor();
    assert.equal(await guest.locator('iframe').count(), 0);
    await host.routeWebSocket('**/socket.io/**', (socket) => socket.close());
    await host.reload();
    await host.getByText('Participants - 2/2', { exact: true }).waitFor();
    await host.getByText('Start movie', { exact: true }).click();
    await guest.locator('iframe').waitFor();
    assert.equal(await guest.locator('iframe').getAttribute('src'), await host.locator('iframe').getAttribute('src'));
    assert.equal(await guest.locator('iframe').getAttribute('allowfullscreen'), null);
    await guest.getByLabel('Fullscreen movie', { exact: true }).click();
    await guest.waitForFunction(() => Boolean(document.fullscreenElement));
    assert.equal(await guest.getByLabel('Unmute microphone').filter({ visible: true }).count(), 1);
    await guest.evaluate(() => document.exitFullscreen());
    await guest.reload(); await guest.locator('iframe').waitFor();
    await host.screenshot({ path: path.join(require('node:os').tmpdir(), 'togetherflix-watch-party-desktop.png'), fullPage: true });
    await guest.screenshot({ path: path.join(require('node:os').tmpdir(), 'togetherflix-watch-party-mobile.png'), fullPage: true });
    await host.close();
    host = await context('host', { width: 1440, height: 1080 });
    await host.goto(`${base}/movie/550`);
    await host.getByText('Direct synchronized source', { exact: true }).click();
    await host.getByText('Watch with Party', { exact: true }).filter({ visible: true }).click();
    await host.waitForURL(/\/room\/TF-/);
    const directCode = host.url().match(/\/room\/(TF-[A-Z2-9]{4})/)[1];
    await guest.goto(`${base}/party/${directCode}`);
    await guest.waitForURL(new RegExp(`/room/${directCode}`));
    await host.waitForFunction(() => [...document.querySelectorAll('div')].some((element) => element.textContent === '2/2 viewers ready'));
    assert.equal(await guest.getByText('Start movie', { exact: true }).count(), 0);
    assert.equal(await guest.getByText('+10s', { exact: true }).count(), 0);
    await host.getByText('Start movie', { exact: true }).click();
    await guest.waitForFunction(() => { const video = document.querySelector('video'); return video && !video.paused && video.currentTime > 0; });
    assert.equal(await guest.locator('video').evaluate((video) => video.controls), false);
    await host.getByText('Pause movie', { exact: true }).click();
    await guest.waitForFunction(() => document.querySelector('video')?.paused === true);
    await host.getByText('Party tools', { exact: true }).click();
    await guest.getByText('Party tools', { exact: true }).click();
    await host.getByText('Room chat', { exact: true }).click();
    await guest.getByText('Room chat', { exact: true }).click();
    await host.getByPlaceholder('Send a whisper...').fill('AnnahFlix movie night');
    await host.getByPlaceholder('Send a whisper...').press('Enter');
    await guest.getByText('AnnahFlix movie night', { exact: true }).waitFor();
    const login = await fetch(`${base}/api/auth/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'guest@example.test', password: 'test-password' }) });
    assert.equal(login.status, 200);
    await guest.waitForURL(/\/login/);
    await guest.getByText('Your account was signed in on another device.', { exact: true }).waitFor();
    assert.deepEqual(errors, []);
    console.log('Browser checks passed: AnnahFlix branding, clean Watch Only, provider selection, party opening, fullscreen, direct playback, party chat, and single-device sign-out.');
  } finally { await browser.close(); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
